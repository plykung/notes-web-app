const tables: Record<Language, Record<StringKey, string>> = { en, th };

/** The text for `key` in the current language, with {placeholders} filled in. */
export function t(key: StringKey, vars: Record<string, string | number> = {}): string {
  const text = tables[getSettings().language][key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));
}

/** "1 change" / "3 changes" in the current language. */
export const changes = (n: number) => (n === 1 ? t("change1") : t("changeN", { n }));

/** The locale for dates and times. */
export const locale = () => (getSettings().language === "th" ? "th-TH" : "en-GB");

/**
 * Fills static page text from data attributes: data-i18n (text),
 * data-i18n-title (tooltip and accessible name), data-i18n-placeholder.
 */
export function translatePage(doc = document) {
  doc.documentElement.lang = getSettings().language;
  for (const el of doc.querySelectorAll<HTMLElement>("[data-i18n]")) el.textContent = t(el.dataset.i18n as StringKey);
  for (const el of doc.querySelectorAll<HTMLElement>("[data-i18n-title]")) {
    const text = t(el.dataset.i18nTitle as StringKey);
    el.title = text;
    el.setAttribute("aria-label", text);
  }
  for (const el of doc.querySelectorAll<HTMLInputElement>("[data-i18n-placeholder]")) {
    el.placeholder = t(el.dataset.i18nPlaceholder as StringKey);
    el.setAttribute("aria-label", el.placeholder); // a placeholder alone isn't a label
  }
  for (const el of doc.querySelectorAll<HTMLElement>("[data-i18n-label]")) {
    el.setAttribute("aria-label", t(el.dataset.i18nLabel as StringKey));
  }
  // The legal pages open in Thai unless the app is in English.
  for (const a of doc.querySelectorAll<HTMLAnchorElement>("a[data-legal]")) {
    a.href = `/${a.dataset.legal}.html${getSettings().language === "en" ? "?lang=en" : ""}`;
  }
}

/** "26 Oct 2026, 14:32" in the current language. */
export const formatDateTime = (iso: string) =>
  new Intl.DateTimeFormat(locale(), { dateStyle: "medium", timeStyle: "short" }).format(new Date(iso));
